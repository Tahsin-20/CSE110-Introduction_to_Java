public class Task01{
	public static void main(String[]args){

        //Task01(a)
		int x=24;
		while(x>=-6){
			if(x>-6){
				System.out.print(x+", ");
			}
			else{
				System.out.print(x);
			}
			x=x-6;
		}

        //Task01(b)
        int y=-10;
		while(y<=20){
			if(y<20){
				System.out.print(y+", ");
			}
			else{
				System.out.print(y);
			}
			y=y+5;
		}
	}
}